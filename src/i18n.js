export function localText(language, key) {
  const index = keys.indexOf(key);
  return (
    (rows[language] || rows.en)[index] ||
    rows.en[index] ||
    rows.en[keys.indexOf("failed")]
  );
}
export function hostText(sdk, key, fallback, params) {
  const text = sdk.i18n.t(key, params);
  return text && text !== key ? text : fallback;
}
